package com.example.domain

import java.util.Locale

data class TraditionalMetalUnit(
  val name: String,
  val grams: Double,
)

data class CountryMarket(
  val isoCode: String,
  val name: String,
  val flag: String,
  val currencyCode: String,
  val localUnit: TraditionalMetalUnit? = null,
) {
  fun localizedName(locale: Locale): String {
    val display = Locale.Builder().setRegion(isoCode).build().getDisplayCountry(locale)
    return if (display.isNullOrBlank() || display.equals(isoCode, ignoreCase = true)) name else display
  }
}

